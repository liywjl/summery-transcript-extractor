export type CaptionTrack = {
  baseUrl: string;
  languageCode: string;
  kind?: string;
  name?: { simpleText?: string; runs?: { text: string }[] };
};

function baseLanguage(code: string): string {
  return code.toLowerCase().split("-")[0];
}

function isAutoGenerated(track: CaptionTrack): boolean {
  return track.kind === "asr";
}

function speaks(track: CaptionTrack, language: string): boolean {
  return baseLanguage(track.languageCode) === baseLanguage(language);
}

export function chooseCaptionTrack(tracks: CaptionTrack[], preferredLanguages: readonly string[]): CaptionTrack | undefined {
  const written = tracks.filter((track) => !isAutoGenerated(track));
  const autoGenerated = tracks.filter(isAutoGenerated);

  for (const language of preferredLanguages) {
    const match = written.find((track) => speaks(track, language)) ?? autoGenerated.find((track) => speaks(track, language));

    if (match) {
      return match;
    }
  }

  return autoGenerated[0] ?? written[0];
}

export function captionTrackLabel(track: CaptionTrack): string {
  const runsText = track.name?.runs?.map((run) => run.text).join("");

  return track.name?.simpleText ?? runsText ?? track.languageCode;
}
